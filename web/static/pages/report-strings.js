const DICTS = { en: EN, uk: UK, es: ES };

export const reportLang = (lang) => (REPORT_LANGS.includes(lang) ? lang : "en");

/** t(key, vars) and tn(key, vars with n) for one report language; a missing key falls back to English. */
export function translator(lang) {
  const code = reportLang(lang);
  const dict = DICTS[code];
  const plural = new Intl.PluralRules(LOCALES[code]);
  const fill = (text, vars) => text.replace(/\{(\w+)\}/g, (whole, name) => vars[name] ?? whole);
  const t = (key, vars = {}) => fill(dict[key] ?? EN[key] ?? key, vars);
  const tn = (key, vars) => {
    const form = `${key}_${plural.select(vars.n)}`;
    const text = dict[form] ?? dict[`${key}_other`] ?? EN[`${key}_${new Intl.PluralRules("en").select(vars.n)}`] ?? key;
    return fill(text, vars);
  };
  return { lang: code, locale: LOCALES[code], t, tn };
}

